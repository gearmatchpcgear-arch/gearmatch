/**
 * gaming_chairs.csv（B〜M列相当）を読み込み lib/gaming-chairs-csv-data.generated.ts を生成
 * Usage: npx tsx scripts/import-gaming-chairs-csv.mjs [csvPath]
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { parseGamingChairShapeCell } from "../lib/gaming-chair-csv-shape.ts"
import { formatDimensions } from "../lib/gaming-chair-dimension-display.ts"

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

function collectListableGamingChairIds() {
  const libDir = path.join(root, "lib")
  const files = fs
    .readdirSync(libDir)
    .filter(
      (name) =>
        name.endsWith(".ts") &&
        !name.includes("csv-data") &&
        !name.includes("csv-shape") &&
        (name.startsWith("gaming-chair") || name === "gaming-chairs.ts"),
    )
  const idRe = /\bid:\s*"(chair-[^"]+)"/g
  const ids = new Set()
  for (const file of files) {
    const text = fs.readFileSync(path.join(libDir, file), "utf8")
    for (const match of text.matchAll(idRe)) ids.add(match[1])
  }
  return ids
}
const defaultCsv = path.join(root, "gaming_chairs.csv")
const csvPath = process.argv[2] ?? defaultCsv
const outPath = path.join(root, "lib", "gaming-chairs-csv-data.generated.ts")

function parseCsv(text) {
  const rows = []
  let row = []
  let field = ""
  let inQuotes = false

  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else {
          inQuotes = false
        }
      } else {
        field += c
      }
      continue
    }

    if (c === '"') {
      inQuotes = true
      continue
    }
    if (c === ",") {
      row.push(field)
      field = ""
      continue
    }
    if (c === "\r") continue
    if (c === "\n") {
      row.push(field)
      if (row.some((cell) => cell.trim() !== "")) rows.push(row)
      row = []
      field = ""
      continue
    }
    field += c
  }
  row.push(field)
  if (row.some((cell) => cell.trim() !== "")) rows.push(row)
  return rows
}

function parseNumber(raw) {
  const t = String(raw ?? "").trim()
  if (!t) return null
  const n = Number(t.replace(/,/g, ""))
  return Number.isFinite(n) ? n : null
}

function normalizeMultilineField(value) {
  return String(value ?? "")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .trim()
}

function escapeTsString(value) {
  return normalizeMultilineField(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
}

const raw = fs.readFileSync(csvPath, "utf8").replace(/^\uFEFF/, "")
const table = parseCsv(raw)
if (table.length < 2) {
  console.error("CSV has no data rows:", csvPath)
  process.exit(1)
}

const headers = table[0].map((h) => h.trim())
const idx = (name) => headers.indexOf(name)

const col = {
  id: idx("ID"),
  name: idx("商品名"),
  description: idx("商品説明"),
  brand: idx("メーカー"),
  price: idx("価格"),
  material: idx("素材"),
  shape: idx("形状"),
  maxReclining: idx("最大リクライニング角度"),
  frameType: idx("フレームの種類"),
  ottoman: idx("オットマンの有無"),
  dimensions: idx("寸法"),
  rating: idx("星"),
  reviewCount: idx("レビュー数"),
}

for (const [key, i] of Object.entries(col)) {
  if (i < 0 && key !== "dimensions" && key !== "rating" && key !== "reviewCount") {
    console.error(`Missing column for ${key}. Headers:`, headers)
    process.exit(1)
  }
}

const catalogIds = collectListableGamingChairIds()

const byId = {}
let skippedInvalidId = 0

for (const cells of table.slice(1)) {
  const id = (cells[col.id] ?? "").trim()
  if (!id) continue
  if (!/^chair-/.test(id)) {
    skippedInvalidId++
    continue
  }

  const shapeCell = (cells[col.shape] ?? "").trim()
  const { shape, backrestWidth } = parseGamingChairShapeCell(shapeCell)

  byId[id] = {
    id,
    name: (cells[col.name] ?? "").trim().replace(/\s+/g, " "),
    description: (cells[col.description] ?? "").trim().replace(/\s+/g, " "),
    brand: (cells[col.brand] ?? "").trim(),
    price: parseNumber(cells[col.price]),
    material: (cells[col.material] ?? "").trim(),
    shape,
    backrestWidth,
    maxReclining: (cells[col.maxReclining] ?? "").trim(),
    frameType: (cells[col.frameType] ?? "").trim(),
    ottoman: (cells[col.ottoman] ?? "").trim(),
    dimensions:
      col.dimensions >= 0
        ? (() => {
            const raw = normalizeMultilineField(cells[col.dimensions])
            if (!raw) return ""
            const formatted = formatDimensions(raw)
            return formatted === "-" ? "" : formatted
          })()
        : "",
    rating: col.rating >= 0 ? parseNumber(cells[col.rating]) : null,
    reviewCount: col.reviewCount >= 0 ? parseNumber(cells[col.reviewCount]) : null,
  }
}

const lines = [
  "/** Auto-generated by scripts/import-gaming-chairs-csv.mjs — do not edit */",
  "export const GAMING_CHAIRS_CSV_BY_ID: Record<string, {",
  "  id: string",
  "  name: string",
  "  description: string",
  "  brand: string",
  "  price: number | null",
  "  material: string",
  "  shape: string",
  "  backrestWidth: string | null",
  "  maxReclining: string",
  "  frameType: string",
  "  ottoman: string",
  "  dimensions: string",
  "  rating: number | null",
  "  reviewCount: number | null",
  "}> = {",
]

for (const row of Object.values(byId).sort((a, b) => a.id.localeCompare(b.id))) {
  lines.push(`  "${escapeTsString(row.id)}": {`)
  lines.push(`    id: "${escapeTsString(row.id)}",`)
  lines.push(`    name: "${escapeTsString(row.name)}",`)
  lines.push(`    description: "${escapeTsString(row.description)}",`)
  lines.push(`    brand: "${escapeTsString(row.brand)}",`)
  lines.push(`    price: ${row.price ?? "null"},`)
  lines.push(`    material: "${escapeTsString(row.material)}",`)
  lines.push(`    shape: "${escapeTsString(row.shape)}",`)
  lines.push(`    backrestWidth: ${row.backrestWidth ? `"${escapeTsString(row.backrestWidth)}"` : "null"},`)
  lines.push(`    maxReclining: "${escapeTsString(row.maxReclining)}",`)
  lines.push(`    frameType: "${escapeTsString(row.frameType)}",`)
  lines.push(`    ottoman: "${escapeTsString(row.ottoman)}",`)
  lines.push(`    dimensions: "${escapeTsString(row.dimensions)}",`)
  lines.push(`    rating: ${row.rating ?? "null"},`)
  lines.push(`    reviewCount: ${row.reviewCount ?? "null"},`)
  lines.push("  },")
}

lines.push("}", "")

fs.writeFileSync(outPath, lines.join("\n"), "utf8")
const importedIds = new Set(Object.keys(byId))
const csvNotInCatalog = [...importedIds].filter((id) => !catalogIds.has(id)).sort()
const catalogNotInCsv = [...catalogIds].filter((id) => !importedIds.has(id)).sort()
console.log(`Imported ${importedIds.size} rows from ${csvPath}`)
if (skippedInvalidId > 0) {
  console.log(`Skipped ${skippedInvalidId} CSV row(s) without a chair-* id`)
}
if (csvNotInCatalog.length > 0) {
  console.warn(
    `CSV has ${csvNotInCatalog.length} id(s) not found in lib gaming-chair catalog (first: ${csvNotInCatalog.slice(0, 5).join(", ")})`,
  )
}
if (catalogNotInCsv.length > 0) {
  console.warn(
    `Catalog has ${catalogNotInCsv.length} gaming-chair id(s) missing from CSV (first: ${catalogNotInCsv.slice(0, 5).join(", ")})`,
  )
}
console.log(`Wrote ${outPath}`)
