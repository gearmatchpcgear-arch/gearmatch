/**
 * Sync mouse list from mouse_products.csv:
 * - Copy canonical CSV to data/mouse_products.csv
 * - Regenerate lib/mouse-products-catalog.generated.ts (exclude I列「〇」, 商品説明)
 * - Update tagline in lib/*.ts for existing mouse gadgets
 *
 * Usage:
 *   npx tsx scripts/sync-mouse-from-products-csv.mjs [csvPath]
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { allSourceGadgets } from "../lib/gadgets.ts"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, "..")
const DATA_CSV = path.join(ROOT, "data", "mouse_products.csv")
const GENERATED_TS = path.join(ROOT, "lib", "mouse-products-catalog.generated.ts")
const EXCLUDED_JSON = path.join(ROOT, "data", "mouse-catalog-excluded-ids.json")

const SOURCE_CANDIDATES = [
  process.argv.find((a) => !a.startsWith("-") && a.endsWith(".csv")),
  path.join(ROOT, "mouse_products.csv"),
  DATA_CSV,
  "D:/ダウンロード/mouse_products - mouse_products.csv",
  "D:/ダウンロード/mouse_products.csv",
].filter(Boolean)

const CSV_PATH = SOURCE_CANDIDATES.find((p) => fs.existsSync(p))
if (!CSV_PATH) {
  console.error("mouse_products.csv not found")
  process.exit(1)
}

const EXISTING_MOUSE_IDS = new Set(
  allSourceGadgets.filter((g) => g.category === "mouse").map((g) => g.id),
)

function parseCsvLine(line) {
  const cols = []
  let cur = ""
  let inQ = false
  for (let i = 0; i < line.length; i++) {
    const c = line[i]
    if (inQ) {
      if (c === '"' && line[i + 1] === '"') {
        cur += '"'
        i++
      } else if (c === '"') inQ = false
      else cur += c
    } else if (c === ",") {
      cols.push(cur)
      cur = ""
    } else if (c === '"') inQ = true
    else cur += c
  }
  cols.push(cur)
  return cols
}

function isExcludeMark(value) {
  const t = String(value ?? "").trim()
  return t === "〇" || t === "○" || t === "◯"
}

function normalizeHeader(h) {
  return String(h ?? "")
    .replace(/^\uFEFF/, "")
    .trim()
}

function findColumnIndex(headers, names) {
  for (const name of names) {
    const idx = headers.findIndex((h) => normalizeHeader(h) === name)
    if (idx >= 0) return idx
  }
  return -1
}

function loadRows() {
  const text = fs.readFileSync(CSV_PATH, "utf8").replace(/^\uFEFF/, "")
  const lines = text.trim().split(/\r?\n/)
  if (lines.length < 2) return { rows: [], headers: [] }

  const headers = parseCsvLine(lines[0]).map(normalizeHeader)
  const idIdx = findColumnIndex(headers, ["ID", "id"])
  const descIdx = findColumnIndex(headers, ["商品説明", "fullTitle", "description"])
  let excludeIdx = headers.findIndex(
    (h) => h === "" || /^Unnamed:\s*8$/i.test(h) || h === "除外" || h === "一覧除外",
  )
  if (excludeIdx < 0 && headers.length > 8) {
    excludeIdx = 8
  }

  const rows = []
  for (const line of lines.slice(1)) {
    const cols = parseCsvLine(line)
    const id = cols[idIdx]?.trim()
    if (!id) continue
    const description = (cols[descIdx] ?? "").trim()
    const listExcluded = excludeIdx >= 0 && isExcludeMark(cols[excludeIdx])
    rows.push({ id, description, listExcluded })
  }
  return { rows, headers, excludeIdx }
}

function escapeTsString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')
}

function writeGenerated(rows) {
  const byId = {}
  const excluded = []
  for (const row of rows) {
    byId[row.id] = { description: row.description, listExcluded: row.listExcluded }
    if (row.listExcluded) excluded.push(row.id)
  }
  excluded.sort()

  const entries = rows
    .map((row) => {
      const desc = escapeTsString(row.description)
      return `  "${row.id}": { description: "${desc}", listExcluded: ${row.listExcluded} },`
    })
    .join("\n")

  const ts = `/** Generated by scripts/sync-mouse-from-products-csv.mjs — do not edit */
export const MOUSE_CATALOG_EXCLUDED_IDS: readonly string[] = ${JSON.stringify(excluded, null, 2)} as const

export const MOUSE_CATALOG_EXCLUDED_ID_SET = new Set<string>(MOUSE_CATALOG_EXCLUDED_IDS)

export const MOUSE_PRODUCTS_CSV_BY_ID: Record<
  string,
  { description: string; listExcluded: boolean }
> = {
${entries}
}
`
  fs.writeFileSync(GENERATED_TS, ts, "utf8")
  fs.mkdirSync(path.dirname(EXCLUDED_JSON), { recursive: true })
  fs.writeFileSync(EXCLUDED_JSON, `${JSON.stringify(excluded, null, 2)}\n`, "utf8")
  return { excludedCount: excluded.length, rowCount: rows.length }
}

function replaceQuotedField(block, field, value) {
  const re = new RegExp(`(${field}: ")([^"]*)(")`)
  if (!re.test(block)) return { block, changed: false }
  const next = block.replace(re, `$1${escapeTsString(value)}$3`)
  return { block: next, changed: next !== block }
}

function applyTaglinesToLib(rows) {
  const byId = new Map(rows.map((r) => [r.id, r]))
  let total = 0
  for (const file of fs.readdirSync(path.join(ROOT, "lib"))) {
    if (!file.endsWith(".ts")) continue
    const filePath = path.join(ROOT, "lib", file)
    let src = fs.readFileSync(filePath, "utf8")
    if (!src.includes('category: "mouse"')) continue

    let updated = 0
    const blockRe = /\{[\s\S]*?id: "([^"]+)"[\s\S]*?category: "mouse"[\s\S]*?\n  \}(?:,|\n|\])/g
    src = src.replace(blockRe, (block, id) => {
      const row = byId.get(id)
      if (!row?.description || !EXISTING_MOUSE_IDS.has(id)) return block
      const { block: next, changed } = replaceQuotedField(block, "tagline", row.description)
      if (changed) updated++
      return next
    })
    if (updated > 0) {
      fs.writeFileSync(filePath, src)
      console.log(`${file}: ${updated} taglines updated`)
      total += updated
    }
  }
  return total
}

function copyCanonicalCsv() {
  if (path.resolve(CSV_PATH) === path.resolve(DATA_CSV)) return
  fs.mkdirSync(path.dirname(DATA_CSV), { recursive: true })
  fs.copyFileSync(CSV_PATH, DATA_CSV)
}

const { rows, headers, excludeIdx } = loadRows()
console.log(`Source: ${CSV_PATH}`)
console.log(`Headers (${headers.length}): ${headers.join(" | ")}`)
console.log(`Exclude column index: ${excludeIdx}`)
copyCanonicalCsv()
console.log(`Canonical CSV: ${DATA_CSV}`)

const { excludedCount, rowCount } = writeGenerated(rows)
console.log(`Catalog rows: ${rowCount}, excluded (〇): ${excludedCount}`)

const taglineUpdates = applyTaglinesToLib(rows)
console.log(`Tagline updates in lib: ${taglineUpdates}`)
