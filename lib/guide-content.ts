import type { CategoryId } from "@/lib/gadgets"

export type GuidePointBullet = {
  label: string
  text: string
}

export type GuidePointSegment =
  | { type: "text"; value: string }
  | { type: "strong"; value: string }

export type GuidePointSubCard = {
  title: string
  text: string
  /** タイトル直下の補助行（解像度表記など） */
  kicker?: string
  /** タイトル直後の小さな補足（例: （定番）） */
  titleSuffix?: string
  /** サブカード内の補足（※〜） */
  note?: string
  /** 本文（strong 等） */
  textSegments?: GuidePointSegment[]
}

export type GuidePoint = {
  head: string
  /** プレーン文（descSegments 未指定時） */
  desc?: string
  /** 説明文（strong 等のインライン強調） */
  descSegments?: GuidePointSegment[]
  bullets?: GuidePointBullet[]
  /** コンパクトな補足カード */
  subCards?: GuidePointSubCard[]
  /** 3 でカード内を sm:grid-cols-3 の横並びに */
  subCardsColumns?: 1 | 3
  /** plain = 枠線なしテキスト横並び（モニターガイド向け） */
  subCardsVariant?: "boxed" | "plain"
  /** 注意書き（amber ボックス・プレーン） */
  callout?: string
  /** 注意書き（amber ボックス・インライン強調） */
  calloutSegments?: GuidePointSegment[]
  /** two-column レイアウトで md:col-span-2 */
  fullWidth?: boolean
}

export type GuidePointsLayout =
  | "single-column"
  | "two-column"
  | "three-column"
  | "four-column"
  /** 横長カードを縦に積む（ゲーミングチェアガイド等） */
  | "stacked-wide"

export type GuideContent = {
  title: string
  titleIcon?: string
  subtitle?: string
  /** セクション全体をカード風ボックスで囲む */
  boxed?: boolean
  pointsLayout?: GuidePointsLayout
  points: GuidePoint[]
}

